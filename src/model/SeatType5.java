package model;

import java.math.BigDecimal;

public class SeatType5 {
    private int id;
    private String loaiGhe;
    private BigDecimal phuThu;
    private String moTa;

    public int getId() { return id; }
    public void setId(int id) { this.id = id; }
    public String getLoaiGhe() { return loaiGhe; }
    public void setLoaiGhe(String loaiGhe) { this.loaiGhe = loaiGhe; }
    public BigDecimal getPhuThu() { return phuThu; }
    public void setPhuThu(BigDecimal phuThu) { this.phuThu = phuThu; }
    public String getMoTa() { return moTa; }
    public void setMoTa(String moTa) { this.moTa = moTa; }
}
